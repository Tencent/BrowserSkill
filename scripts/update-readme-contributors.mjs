#!/usr/bin/env node
/** Refresh both README avatar walls from GitHub's public contributors API.
 * Usage: node scripts/update-readme-contributors.mjs [--input contributors.json]
 * GITHUB_TOKEN (or GH_TOKEN) authenticates API requests when available.
 * Only GitHub-linked contributors have profile avatars; anonymous authors are
 * still represented by the linked GitHub contribution history.
 */
import { execFileSync } from "node:child_process";
import { readFileSync } from "node:fs";
import { readFile, writeFile } from "node:fs/promises";
import { pathToFileURL } from "node:url";
import { parseArgs } from "node:util";

const root = new URL("../", import.meta.url);
const start = "<!-- CONTRIBUTORS:START -->";
const end = "<!-- CONTRIBUTORS:END -->";
const readmes = ["README.md", "README.zh-CN.md"];

export async function fetchContributors({
  token = process.env.GITHUB_TOKEN || process.env.GH_TOKEN,
  fetchImpl = fetch,
} = {}) {
  const contributors = [];
  for (let page = 1; page <= 100; page += 1) {
    const response = await fetchImpl(
      `https://api.github.com/repos/Tencent/BrowserSkill/contributors?per_page=100&page=${page}`,
      {
        headers: {
          Accept: "application/vnd.github+json",
          ...(token ? { Authorization: `Bearer ${token}` } : {}),
        },
        signal: AbortSignal.timeout(30_000),
      },
    );
    if (!response.ok) {
      throw new Error(`GitHub contributors request failed: ${response.status}`);
    }
    const batch = await response.json();
    if (!Array.isArray(batch)) throw new Error("Unexpected contributors response");
    contributors.push(...batch);
    if (batch.length < 100) return contributors;
  }
  throw new Error("Contributor pagination exceeded 100 pages; no README files were changed");
}

export function splitContributorBlock(markdown, name = "README") {
  const from = markdown.indexOf(start);
  const to = markdown.indexOf(end);
  if (
    from < 0 ||
    to < from ||
    markdown.indexOf(start, from + start.length) !== -1 ||
    markdown.indexOf(end, to + end.length) !== -1
  ) {
    throw new Error(`Expected exactly one contributor marker pair in ${name}`);
  }
  return {
    before: markdown.slice(0, from),
    block: markdown.slice(from, to + end.length),
    after: markdown.slice(to + end.length),
  };
}

export async function updateReadmes(data, directory = root) {
  if (!Array.isArray(data)) throw new Error("Unexpected contributors response");
  const people = new Map();
  for (const person of data) {
    if (person.type === "Anonymous" || person.type === "Bot") continue;
    if (
      person.type !== "User" ||
      !/^[a-z0-9][a-z0-9-]{0,38}$/i.test(person.login ?? "") ||
      !Number.isSafeInteger(person.id) ||
      person.id <= 0
    ) {
      throw new Error("Invalid GitHub contributor record; no README files were changed");
    }
    people.set(person.id, person);
  }
  if (people.size === 0) throw new Error("No GitHub contributors returned");

  // Read and validate both documents before writing either language.
  const documents = await Promise.all(
    readmes.map(async (name) => {
      const path = new URL(name, directory);
      const markdown = await readFile(path, "utf8");
      return { name, path, markdown, ...splitContributorBlock(markdown, name) };
    }),
  );
  // Keep the existing wall order when contribution counts change. New accounts
  // are appended in stable GitHub ID order; renamed accounts keep their place.
  const contributors = [];
  for (const match of documents[0].block.matchAll(/avatars\.githubusercontent\.com\/u\/(\d+)\?/g)) {
    const id = Number(match[1]);
    if (people.has(id)) contributors.push(people.get(id));
    people.delete(id);
  }
  contributors.push(...[...people.values()].sort((a, b) => a.id - b.id));
  const rows = [
    start,
    "<!-- Generated by node scripts/update-readme-contributors.mjs -->",
    '<p align="center">',
  ];
  for (const [index, person] of contributors.entries()) {
    const login = encodeURIComponent(person.login);
    rows.push(
      `  <a href="https://github.com/${login}"><img src="https://avatars.githubusercontent.com/u/${person.id}?s=96&amp;v=4" width="48" height="48" alt="${login}" title="${login}" /></a>`,
    );
    if ((index + 1) % 10 === 0 && index < contributors.length - 1) rows.push("  <br />");
  }
  rows.push("</p>", end);
  const block = rows.join("\n");
  const changed = [];
  for (const document of documents) {
    const content = document.before + block + document.after;
    if (content === document.markdown) continue;
    await writeFile(document.path, content);
    changed.push(document.name);
  }
  return { count: contributors.length, changed };
}

// Check a pending update or revision range before committing or reviewing it.
// Refuse changes outside the marked contributor blocks.
export function verifyContributorChanges(base = "HEAD", head, directory = root) {
  const git = (...args) => execFileSync("git", args, { cwd: directory, encoding: "utf8" });
  const names = git("diff", "--name-only", base, ...(head ? [head] : []), "--").trim();
  for (const name of names ? names.split("\n") : []) {
    if (!readmes.includes(name))
      throw new Error(`Refusing an update outside contributor blocks: ${name}`);
    const before = splitContributorBlock(git("show", `${base}:${name}`), name);
    const after = splitContributorBlock(
      head ? git("show", `${head}:${name}`) : readFileSync(new URL(name, directory), "utf8"),
      name,
    );
    if (before.before !== after.before || before.after !== after.after) {
      throw new Error(`Refusing an update outside contributor blocks: ${name}`);
    }
  }
}

async function main() {
  const { values } = parseArgs({
    options: {
      input: { type: "string" },
      "verify-only": { type: "boolean" },
      base: { type: "string", default: "HEAD" },
      head: { type: "string" },
    },
  });
  if (values["verify-only"]) return verifyContributorChanges(values.base, values.head);
  const data = values.input
    ? JSON.parse(await readFile(values.input, "utf8"))
    : await fetchContributors();
  const result = await updateReadmes(data);
  console.log(
    result.changed.length
      ? `Updated ${result.changed.join(", ")} with ${result.count} contributor avatars.`
      : `Contributor avatars unchanged (${result.count} accounts).`,
  );
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  main().catch((error) => {
    console.error(error.message);
    process.exitCode = 1;
  });
}
